import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = `${root}src/assets/fonts/icons/arcane-chronicles.icomoon.json`;

const { glyphs } = JSON.parse(readFileSync(source, 'utf8'));

const toKebab = (name) => name.replace(/_/g, '-').toLowerCase();
const shortName = (name) => toKebab(name.replace(/^[^_]+_/, ''));

const shortCounts = new Map();
for (const { extras } of glyphs) {
  const short = shortName(extras.name);
  shortCounts.set(short, (shortCounts.get(short) ?? 0) + 1);
}

const icons = glyphs
  .map(({ extras }) => {
    const short = shortName(extras.name);
    return {
      name: shortCounts.get(short) > 1 ? toKebab(extras.name) : short,
      code: extras.codePoint.toString(16),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const header = '// Generated by scripts/generate-icons.mjs, do not edit manually.\n';

writeFileSync(
  `${root}src/styles/variables/_icons.scss`,
  `${header}
$icons-names: (
${icons.map(({ name, code }) => `  '${name}': '\\${code}',`).join('\n')}
);
`,
);

console.log(`${icons.length} icônes générées.`);
